// Extracts roll ranges, item names and inventory metadata from the revised DMG.
// node scripts/build-treasure-data.mjs [book-xdmg.json items.json]
import { readFile, writeFile } from 'node:fs/promises';

const base = 'https://raw.githubusercontent.com/5etools-mirror-3/5etools-src/main/data/';
const read = async (local, path) => {
  if (local) return JSON.parse(await readFile(local, 'utf8'));
  const response = await fetch(base + path);
  if (!response.ok) throw new Error(`Cannot read ${path}: ${response.status}`);
  return response.json();
};
const [book, items] = await Promise.all([
  read(process.argv[2], 'book/book-xdmg.json'),
  read(process.argv[3], 'items.json'),
]);
const itemByKey = new Map(items.item.map((item) => [`${item.name}|${item.source}`.toLowerCase(), item]));
const valuables = {};
const magic = {};
const details = {};
const rarities = { common: 'common', uncommon: 'uncommon', rare: 'rare', 'very rare': 'veryRare', legendary: 'legendary' };

function collect(entry) {
  if (!entry || typeof entry !== 'object') return;
  const caption = entry.caption ?? '';
  if (entry.type === 'table' && /^[\d,]+ GP (Gemstones|Art Objects)$/.test(caption)) {
    valuables[caption] = entry.rows.map(([, text]) => {
      const [, name] = text.match(/\{@item ([^|}]+)/);
      return name[0].toUpperCase() + name.slice(1);
    });
  }
  if (entry.type === 'table' && /^(Arcana|Armaments|Implements|Relics) - /.test(caption)) {
    magic[caption] = entry.rows.map(([range, text]) => {
      const tags = [...text.matchAll(/\{@item ([^|}]+)\|([^|}]+)/g)];
      if (!tags.length) throw new Error(`Missing item in ${caption}: ${text}`);
      const names = tags.slice(tags.length > 1 ? 1 : 0).map(([, name, source]) => {
        const item = itemByKey.get(`${name}|${source}`.toLowerCase());
        if (item) {
          const { value, weight, reqAttune, type, rarity, baseItem } = item;
          const consumable = !!item.consumable || /^(P|SC|A)\|/.test(type ?? '') || item.poison === true;
          details[name] = { valueGp: value == null ? undefined : value / 100, weight, attunement: reqAttune, consumable, rarity: rarities[rarity], baseItem: baseItem?.split('|')[0] };
        }
        return name;
      });
      if (names[0].startsWith('Enspelled ') && text.includes('level 6, 7, or 8')) {
        names.splice(0, 1, ...[6, 7, 8].map((level) => `${names[0]} (Level ${level})`));
      }
      return [Number(range.split(/[–-]/).at(-1)) || 100, ...names];
    });
  }
  for (const child of Object.values(entry)) collect(child);
}

collect(book);
if (Object.keys(valuables).length !== 11 || Object.keys(magic).length !== 20) throw new Error('Unexpected DMG table count');
const rows = (tables) => Object.entries(tables).map(([name, entries]) => `  ${JSON.stringify(name)}: [\n${entries.map((entry) => `    ${JSON.stringify(entry)},`).join('\n')}\n  ],`).join('\n');
const properties = Object.entries(details)
  .filter(([, item]) => item.valueGp != null || item.weight != null || item.attunement || item.consumable || item.rarity || item.baseItem)
  .map(([name, item]) => `  ${JSON.stringify(name)}: ${JSON.stringify({ ...item, consumable: item.consumable || undefined })},`).join('\n');

await writeFile(new URL('../src/rules/treasureData.ts', import.meta.url),
  `// Generated by scripts/build-treasure-data.mjs from 5etools revised DMG data.\nimport type { Rarity } from './crafting';\n\nexport const VALUABLE_TABLES: Record<string, string[]> = {\n${rows(valuables)}\n};\n\nexport const MAGIC_TABLES: Record<string, [number, ...string[]][]> = {\n${rows(magic)}\n};\n\nexport const MAGIC_DETAILS: Record<string, { valueGp?: number; weight?: number; attunement?: boolean | string; consumable?: boolean; rarity?: Rarity; baseItem?: string }> = {\n${properties}\n};\n`);
