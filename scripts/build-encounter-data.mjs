// Builds src/rules/encounterData.ts from the 5etools copy of the 2024 Monster Manual.
// Only creatures marked as part of the SRD 5.2 (CC BY 4.0) are kept, and only the facts the
// encounter tables need: name, Challenge Rating, size, creature type, alignment and environments.
//
//   node scripts/build-encounter-data.mjs [path-or-url to bestiary-xmm.json]
import { readFile, writeFile } from 'node:fs/promises';

const SRC = process.argv[2] ?? 'https://raw.githubusercontent.com/5etools-mirror-3/5etools-src/main/data/bestiary/bestiary-xmm.json';
const raw = SRC.startsWith('http') ? await (await fetch(SRC)).text() : await readFile(SRC, 'utf8');
const monsters = JSON.parse(raw).monster.filter((m) => m.srd52);

const ENVS = new Set(['arctic', 'coastal', 'desert', 'forest', 'grassland', 'hill', 'mountain', 'swamp', 'underdark', 'urban', 'underwater', 'any']);
const crOf = (m) => (typeof m.cr === 'object' ? m.cr.cr : m.cr);
const typeOf = (m) => (typeof m.type === 'object' ? m.type.type : m.type);
const alignOf = (m) => {
  const a = (m.alignment ?? []).filter((x) => typeof x === 'string');
  if (a.includes('E')) return 'E';
  if (a.includes('G')) return 'G';
  if (a.includes('U')) return 'U';
  return 'N';
};

const rows = monsters
  .map((m) => [m.name, crOf(m), m.size[0], typeOf(m), alignOf(m), (m.environment ?? []).filter((e) => ENVS.has(e)).join(' ')])
  .filter((r) => r[5])
  .sort((a, b) => a[0].localeCompare(b[0]));

const body = rows.map((r) => `  ${JSON.stringify(r)},`).join('\n');
const out = `// Generated by scripts/build-encounter-data.mjs from the 5etools copy of the 2024 Monster Manual.
// Creatures from the System Reference Document 5.2 by Wizards of the Coast LLC, used under CC BY 4.0.
// Only names, Challenge Ratings, sizes, creature types, alignments and environments are kept: no rules text.

/** [name, CR, size code, creature type, alignment (E evil, G good, N neutral, U unaligned), environments] */
export type SrdRow = [string, string, string, string, 'E' | 'G' | 'N' | 'U', string];

export const SRD_CREATURES: SrdRow[] = [
${body}
];
`;
await writeFile(new URL('../src/rules/encounterData.ts', import.meta.url), out);
console.log(`Wrote ${rows.length} creatures.`);
