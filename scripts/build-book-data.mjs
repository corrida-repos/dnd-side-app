// Builds src/rules/bookData.ts: creatures from other 5etools books for the random encounter tables.
// Keeps only name, Challenge Rating, size, type, alignment, environments and flags (no rules text),
// and leaves out named individuals, entries reprinted in a newer book, creatures with no material-plane
// environment, and (for the 2024 Monster Manual) the creatures already built in from the SRD 5.2.
//
//   node scripts/build-book-data.mjs [local folder holding the bestiary-*.json files]
import { readFile, writeFile } from 'node:fs/promises';

const BASE = 'https://raw.githubusercontent.com/5etools-mirror-3/5etools-src/main/data/bestiary/';
const BOOKS = [
  { src: 'XMM', file: 'bestiary-xmm.json' },
  { src: 'MPMM', file: 'bestiary-mpmm.json' },
  { src: 'FRAiF', file: 'bestiary-fraif.json' },
  { src: 'RHW', file: 'bestiary-rhw.json' },
  { src: 'AU', file: 'bestiary-au.json' },
];
const local = process.argv[2];
const read = async (f) => JSON.parse(local ? await readFile(`${local}/${f}`, 'utf8') : await (await fetch(BASE + f)).text());

const ENVS = new Set(['arctic', 'coastal', 'desert', 'forest', 'grassland', 'hill', 'mountain', 'swamp', 'underdark', 'urban', 'underwater', 'any']);
const crOf = (m) => (typeof m.cr === 'object' ? m.cr.cr : m.cr);
const typeOf = (m) => String(typeof m.type === 'object' ? m.type.type : m.type).toLowerCase();
const alignOf = (m) => {
  const a = (m.alignment ?? []).filter((x) => typeof x === 'string');
  return a.includes('E') ? 'E' : a.includes('G') ? 'G' : a.includes('U') ? 'U' : 'N';
};
const flagsOf = (m) => `${m.legendary ? 'L' : ''}${m.speed?.swim ? 's' : ''}${m.speed?.fly ? 'f' : ''}`;

const out = {};
for (const b of BOOKS) {
  const monsters = (await read(b.file)).monster ?? [];
  out[b.src] = monsters
    .filter((m) => !m.srd52 && !m.isNamedCreature && !m.reprintedAs?.length && m.cr != null && Array.isArray(m.size))
    .map((m) => [m.name, crOf(m), m.size[0], typeOf(m), alignOf(m), (m.environment ?? []).filter((e) => ENVS.has(e)).join(' '), flagsOf(m)])
    .filter((r) => r[5] && r[1] && r[1] !== 'Unknown')
    .sort((a, c) => a[0].localeCompare(c[0]));
  console.log(`${b.src}: ${out[b.src].length}`);
}
const body = Object.entries(out)
  .map(([src, rows]) => `  ${src}: [\n${rows.map((r) => `    ${JSON.stringify(r)},`).join('\n')}\n  ],`)
  .join('\n');
await writeFile(
  new URL('../src/rules/bookData.ts', import.meta.url),
  `// Generated by scripts/build-book-data.mjs from 5etools. Creatures from books outside the SRD, kept only as
// reference facts for the random encounter tables: name, Challenge Rating, size, type, alignment, environments, flags.

import type { SrdRow } from './encounterData';

export const BOOK_CREATURES: Record<string, SrdRow[]> = {
${body}
};
`,
);
